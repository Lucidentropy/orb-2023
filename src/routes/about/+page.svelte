    <h2>Origins</h2>

    <p>It was the summer of 2000. Several legendary franchises were in full swing - big names like Counter-Strike, Unreal Tournament, Diablo II, Starcraft, and Quake III. I was trying them all, and one day discovered Starsiege: Tribes, and I was hooked. It had many elements other games didn't have at the time, like outdoor environments, jetpacks, vehicles, dynamic objectives, and custom maps and mods that didn't need to be downloaded first.</p>    
    <p>Before high-speed internet was broadly available, it was important that you found servers with the lowest ping. When you were playing from Hawaii, however, every server had a high ping. This resulted in most every server's ping being effectively the same to me, so I would choose where I played solely on the community there. I would hop between servers until I eventually found one I liked playing on: a server called Oklahoma RR Tribes.</p>
    <p>I tried joining other clans at the time but was immediately disappointed at how uncool they were to each other. In the spirit of, "Yeah, well… I’m gonna go build my own clan with blackjack,” I thought it over for a few days, then with a few server regulars in tow, we created Orb. There were 4 founding members: Myself, Lucid (at the time known as Raven); Cells; Doom Train; and Vorax-1.</p>
    <p>Orb has since evolved into a multi-game community with real life meet-ups that have included road trips, weddings, and regular get-togethers with people from numerous states.</p>
